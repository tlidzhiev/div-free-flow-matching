import json
from pathlib import Path
from typing import Any, Literal

import grain
import numpy as np

from lab.utils.io import get_root


class KolmogorovDataset(grain.sources.RandomAccessDataSource):
    """
    Velocity fields of the Kolmogorov flow with their conditions (normalized log viscosity),
    generated by 'scripts/generate_data.py'.

    An element is {'x': float32 (X, Y, 2) velocity (u, v) channels-last, 'cond': float32
    scalar}. The arrays are memory-mapped; the maps are opened lazily in each process, so the
    data source is pickled to the grain workers without the data.

    With 'normalize', the velocities are divided by 'u_scale', the RMS velocity of the train
    split from 'meta.json' (the same for all splits): the fields are of unit scale, like the
    noise of the flow. One scale for both components keeps the fields divergence-free;
    multiply by 'u_scale' to get back the physical units.
    """

    def __init__(
        self,
        root: str | Path = 'data/kolmogorov',
        split: Literal['train', 'val', 'test'] = 'train',
        limit: int | None = None,
        normalize: bool = True,
    ) -> None:
        """
        Parameters
        ----------
        root : str or Path, optional
            Dataset directory, relative to the project root (or absolute).
        split : {'train', 'val', 'test'}, optional
            Dataset split.
        limit : int or None, optional
            Keep only the first 'limit' elements.
        normalize : bool, optional
            Divide the velocities by 'u_scale' (the train RMS velocity from 'meta.json').
        """
        if split not in {'train', 'val', 'test'}:
            raise ValueError(f"split must be 'train', 'val', or 'test'; got {split!r}")
        if limit is not None and limit < 0:
            raise ValueError('limit must be non-negative or None')
        self._split_dir = get_root() / root / split
        self.u_scale = self._read_u_scale(get_root() / root / 'meta.json') if normalize else 1.0
        self._fields: np.ndarray | None = None
        self._conditions: np.ndarray | None = None

        fields, conditions = self._arrays()
        if fields.ndim != 4 or fields.shape[-1] != 2:
            raise ValueError(f'Expected fields with shape (N, X, Y, 2), got {fields.shape}')
        if conditions.ndim != 1 or len(conditions) != len(fields):
            raise ValueError('c.npy must contain one scalar condition per velocity field')
        self._length = len(fields) if limit is None else min(limit, len(fields))

    @staticmethod
    def _read_u_scale(meta_path: Path) -> float:
        """
        The velocity scale of the dataset: 'normalization.u_scale' of 'meta.json'.
        """
        with meta_path.open() as f:
            u_scale = json.load(f).get('normalization', {}).get('u_scale')
        if u_scale is None or not u_scale > 0:
            raise ValueError(
                f'{meta_path} has no positive normalization.u_scale (the RMS velocity of the '
                f'train split, got {u_scale!r}): generate the train split, or pass '
                'normalize=False'
            )
        return float(u_scale)

    def _arrays(self) -> tuple[np.ndarray, np.ndarray]:
        if self._fields is None or self._conditions is None:
            self._fields = np.load(self._split_dir / 'fields.npy', mmap_mode='r')
            self._conditions = np.load(self._split_dir / 'c.npy', mmap_mode='r')
        return self._fields, self._conditions

    def __len__(self) -> int:
        return self._length

    def __getitem__(self, index: int) -> dict[str, np.ndarray]:
        if index < 0 or index >= self._length:
            raise IndexError(index)
        fields, conditions = self._arrays()
        return {
            'x': np.asarray(fields[index] / self.u_scale, dtype=np.float32),
            'cond': np.asarray(conditions[index], dtype=np.float32),
        }

    def __getstate__(self) -> dict[str, Any]:
        # The memory maps are not pickled (that would copy the data): reopened on access
        return {**self.__dict__, '_fields': None, '_conditions': None}

    def __repr__(self) -> str:
        return (
            f'{type(self).__name__}(split_dir={str(self._split_dir)!r}, len={self._length}, '
            f'u_scale={self.u_scale:.4g})'
        )
