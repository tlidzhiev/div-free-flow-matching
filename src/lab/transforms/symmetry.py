"""Symmetry augmentations of the Kolmogorov flow on the periodic domain [0, 2pi)^2.

The flow, forced by F = (sin(k_f y), 0), is equivariant under

* T_s: translations in x,                 (u, v)(x, y) -> ( u,  v)( x - s, y),
* S:   shift-reflect,                      (u, v)(x, y) -> (-u,  v)(-x, y + pi / k_f),
* R:   rotation by pi,                     (u, v)(x, y) -> (-u, -v)(-x, -y),

so they map fields of the attractor at a given Reynolds number to fields of the same
distribution: the condition is unchanged. Every element of the generated group has the form

    u'(p) = A u(A p + b),   A = diag(ex, ey),   b = (sx, m pi / k_f),

with ex, ey in {-1, +1}, any sx, and m of the parity of (1 - ex ey) / 2 (the forcing must stay
invariant). On the grid they are exact permutations of the grid points with sign flips of the
components, so a divergence-free field stays divergence-free and band-limited.
"""

from typing import Any

import grain
import numpy as np


class KolmogorovSymmetry(grain.transforms.RandomMap):
    """
    Random symmetry of the Kolmogorov flow applied to the field of an element, as a grain
    random map (NumPy, in the data pipeline).

    The element is sampled uniformly from the subgroup generated by the enabled generators.
    """

    def __init__(
        self,
        k_f: int = 4,
        translate: bool = True,
        shift_reflect: bool = True,
        rotate: bool = True,
        key: str = 'x',
    ) -> None:
        """
        Parameters
        ----------
        k_f : int, optional
            Forcing wavenumber (the shift of S is pi / k_f).
        translate : bool, optional
            Random translations in x by whole grid cells (T_s).
        shift_reflect : bool, optional
            Random powers of the shift-reflect S (it includes the shifts in y by 2 pi / k_f).
        rotate : bool, optional
            Rotation by pi (R) with probability 1/2.
        key : str, optional
            Element entry with the field (X, Y, 2), channels (u, v).
        """
        if k_f < 1:
            raise ValueError(f'k_f must be positive, got {k_f}')
        self.k_f = k_f
        self.translate = translate
        self.shift_reflect = shift_reflect
        self.rotate = rotate
        self.key = key

    def random_map(self, element: dict[str, Any], rng: np.random.Generator) -> dict[str, Any]:
        """
        Transform the field of an element by a random group element.
        """
        x = element[self.key]
        if x.ndim != 3 or x.shape[-1] != 2:
            raise ValueError(f'Expected a field with shape (X, Y, 2), got {x.shape}')
        if not (self.translate or self.shift_reflect or self.rotate):
            return element
        return {**element, self.key: self.apply(x, *self.sample(rng, *x.shape[:2]))}

    def sample(self, rng: np.random.Generator, nx: int, ny: int) -> tuple[int, int, int, int]:
        """
        Sample a group element (ex, ey, sx, sy); the shifts are in grid cells.
        """
        if self.shift_reflect and ny % (2 * self.k_f) != 0:
            raise ValueError(
                f'The shift-reflect needs a grid size in y divisible by 2 * k_f = '
                f'{2 * self.k_f}, got {ny}'
            )
        # R flips both axes: ey = -1 only for the rotated fields
        ey = int(rng.choice((1, -1))) if self.rotate else 1
        if self.shift_reflect:
            # S^m (then R): ex ey = (-1)^m
            m = int(rng.integers(2 * self.k_f))
            ex, sy = ey * (-1) ** m, m * (ny // (2 * self.k_f))
        else:
            ex, sy = ey, 0
        sx = int(rng.integers(nx)) if self.translate else 0
        return ex, ey, sx, sy

    @staticmethod
    def apply(x: np.ndarray, ex: int, ey: int, sx: int, sy: int) -> np.ndarray:
        """
        u'[i, j] = A u[(ex i + sx) mod X, (ey j + sy) mod Y] for one field (X, Y, 2).
        """
        nx, ny = x.shape[:2]
        i = (ex * np.arange(nx) + sx) % nx
        j = (ey * np.arange(ny) + sy) % ny
        return x[np.ix_(i, j)] * np.array([ex, ey], dtype=x.dtype)

    def __repr__(self) -> str:
        return (
            f'{type(self).__name__}(k_f={self.k_f}, translate={self.translate}, '
            f'shift_reflect={self.shift_reflect}, rotate={self.rotate}, key={self.key!r})'
        )
